def seed(workdir):
    script = f"""
import sys
sys.path.insert(0, {str(SERVER_ROOT)!r})
from database.database import SessionLocal
from database.crud import UserCRUD, RepositoryCRUD, UserPermissionCRUD
from app.core.security import hash_password
db = SessionLocal()
for name, role in (("lead", "team_lead"), ("dev", "developer"), ("outsider", "developer")):
    UserCRUD.create_user(db, username=name, role=role, password_hash=hash_password({PASSWORD!r}),
                         email=name + "@e2e.test")
inventory = RepositoryCRUD.create_repository(db, "lead", "inventory", "stock")
other = RepositoryCRUD.create_repository(db, "lead", "secrets", "not for dev")
UserPermissionCRUD.create_permission(db, "dev", inventory.id, "write", "lead")
print(inventory.id, other.id)
"""
    out = subprocess.run([sys.executable, "-c", script], cwd=SERVER_ROOT, env=server_env(workdir),
                         capture_output=True, text=True, encoding="utf-8")
    if out.returncode != 0:
        raise RuntimeError(out.stderr)
    return out.stdout.strip().splitlines()[-1].split()


def session_of(base, username):
    status, body = Api(base).post("/api/auth/login", {"username": username, "password": PASSWORD})
    return body.get("access_token") if status == 200 else None


class Ctx:
    pass


def call(api, method, path, **kw):
    return api._call(method, path, **kw)


def heads(api, repo_id):
    _s, body = api.get(f"/api/repository/{repo_id}/branches")
    return {b["name"]: b["head_commit_id"] for b in body.get("branches", [])}


def push(api, repo_id, author, branch, files, message):
    parent = heads(api, repo_id).get(branch)
    commit_id = hashlib.sha1(f"{repo_id}:{branch}:{message}:{time.time_ns()}".encode()).hexdigest()
    status, body = api.post(f"/api/repository/{repo_id}/push", {
        "branch": branch,
        "commit": {"id": commit_id, "author": author, "message": message,
                   "parent": parent, "parents": [parent] if parent else [],
                   "files": {path: b64(data) for path, data in files.items()},
                   "timestamp": time.strftime("%Y-%m-%dT%H:%M:%S")},
    })
    if status != 200:
        raise RuntimeError(f"push to {branch}: {status} {body}")
    return commit_id


def tree(workdir, commit_id):
    import sqlite3
    import contextlib
    with contextlib.closing(sqlite3.connect(workdir / "e2e.db")) as db:
        rows = db.execute("SELECT file_path FROM commit_files WHERE commit_id = ?", (commit_id,)).fetchall()
    return sorted(r[0].replace("\\", "/") for r in rows)


def wait_job(api, repo_id, timeout=120):
    deadline = time.monotonic() + timeout
    body = {}
    while time.monotonic() < deadline:
        _s, body = api.get(f"/api/repository/{repo_id}/docs-status")
        if body.get("status") in ("completed", "failed"):
            return body
        time.sleep(0.5)
    return body


# --- scenarios ------------------------------------------------------------------------

def scenario_setup(r, c, workdir):
    r.section("1  Setup")
    c.repo, c.other = seed(workdir)
    c.lead = Api(c.base, session_of(c.base, "lead"))
    c.dev = Api(c.base, session_of(c.base, "dev"))
    c.outsider = Api(c.base, session_of(c.base, "outsider"))
    r.check("three users signed in", all(a.token for a in (c.lead, c.dev, c.outsider)))
    push(c.lead, c.repo, "lead", "main", {"app.py": "print('v1')\n", "old.txt": "goes away\n",
                                          "assets/logo.png": PNG, "docs/handwritten.md": "# Ours\n"}, "first")
    c.v1 = push(c.lead, c.repo, "lead", "main", {"app.py": "print('v1')\n", "assets/logo.png": PNG,
                                                  "docs/handwritten.md": "# Ours\n"}, "remove old.txt")
    push(c.lead, c.other, "lead", "main", {"secret.txt": "not yours\n"}, "secret")
    c.foreign = heads(c.lead, c.other)["main"]
    r.check("two repositories with history", bool(c.v1 and c.foreign))


def scenario_branches(r, c):
    r.section("2  Branches")
    url = f"/api/repository/{c.repo}"
    s, _ = c.dev.post(f"{url}/branches", {"name": "feature/login", "from_branch": "main"})
    r.check("a developer creates feature/login", s == 200)
    push(c.lead, c.repo, "lead", "feature/login", {"app.py": "print('v1')\n", "login.py": "login = 1\n", "assets/logo.png": PNG,
                                                   "docs/handwritten.md": "# Ours\n"}, "Add login")
    push(c.lead, c.repo, "lead", "feature/login", {"app.py": "print('v1')\n", "login.py": "login = 2\n", "assets/logo.png": PNG,
                                                   "docs/handwritten.md": "# Ours\n"}, "Polish login")
    c.v2 = push(c.lead, c.repo, "lead", "main", {"app.py": "print('v2')\n", "assets/logo.png": PNG,
                                                  "docs/handwritten.md": "# Ours\n"}, "Fix the login redirect")
    s, body = c.lead.post(f"{url}/pull-requests", {"title": "Login", "source_branch": "feature/login",
                                                   "target_branch": "main"})
    c.pr = body.get("pull_request", {}).get("id")
    r.check("a pull request from feature/login", s == 200 and c.pr)

    s, body = c.dev.get(f"{url}/branches", params={"details": "true"})
    rows = {b["name"]: b for b in body.get("branches", [])}
    login = rows.get("feature/login", {})
    r.check("the list says feature/login is 2 ahead and 1 behind main",
            (login.get("ahead"), login.get("behind")) == (2, 1), login)
    r.check("...with its last commit and author",
            login.get("head_commit", {}).get("message") == "Polish login"
            and login.get("head_commit", {}).get("author") == "lead", login.get("head_commit"))
    r.check("...and the pull request that uses it", [p["id"] for p in login.get("pull_requests", [])] == [c.pr])
    r.check("a developer may write but not manage", body.get("permissions") == {"can_write": True, "can_manage": False},
            body.get("permissions"))

    enc = "feature%2Flogin"
    s, body = c.lead._call("DELETE", f"{url}/branches/{enc}")
    r.check("a branch an open pull request uses is not deleted (409, names the PR)",
            s == 409 and body.get("detail", {}).get("code") == "BRANCH_IN_USE", body)
    s, body = c.lead.put(f"{url}/branches/{enc}/rename", {"new_name": "feature/sign-in"})
    r.check("a name with a slash can be renamed, percent-encoded as the browser sends it",
            s == 200 and body.get("retargeted_pull_requests") == [c.pr], body)
    s, body = c.lead.get(f"{url}/pull-requests/{c.pr}")
    r.check("...and the pull request follows the new name", "feature/sign-in" in json.dumps(body))

    s, _ = c.lead.post(f"{url}/branches", {"name": "spike", "from_branch": "main"})
    tip = push(c.lead, c.repo, "lead", "spike", {"app.py": "print('spike')\n"}, "spike work")
    s, body = c.lead._call("DELETE", f"{url}/branches/spike")
    r.check("deleting answers with the tip, for restoring",
            s == 200 and body.get("branch", {}).get("head_commit_id") == tip, body)
    s, _ = c.lead.post(f"{url}/branches", {"name": "spike", "from_commit": tip})
    r.check("...and the branch comes back at that commit", s == 200 and heads(c.lead, c.repo).get("spike") == tip)

    s, body = c.lead.post(f"{url}/branches", {"name": "leak", "from_commit": c.foreign})
    r.check("a branch cannot start at another repository's commit (404)", s == 404, body)
    s, body = c.lead.put(f"{url}/branches/spike/head", {"head_commit_id": c.foreign})
    r.check("...nor be moved to one (404)", s == 404, body)
    s, body = c.lead.put(f"{url}/branches/spike/head", {"head_commit_id": c.v2, "expected_head_commit_id": c.v1})
    r.check("a move against a stale expectation is refused (409)", s == 409, body)
    s, _ = c.lead.put(f"{url}/branches/nope/default")
    r.check("making a missing branch the default is 404, not 500", s == 404)
    s, _ = c.outsider.get(f"{url}/branches", params={"details": "true"})
    r.check("an outsider cannot list them (403)", s == 403)


def scenario_releases(r, c):
    r.section("3  Tags and releases")
    url = f"/api/repository/{c.repo}"
    s, body = c.lead.post(f"{url}/releases", {"version": "1.0.0", "target": c.v1, "title": "First",
                                              "notes": "Initial release"})
    r.check("a release tags the commit it is aimed at", s == 200 and body["release"]["commit_id"] == c.v1, body)
    s, body = c.lead._call("POST", f"{url}/pull-requests/{c.pr}/merge", json={})
    r.check("the login pull request merges", s == 200, body)
    s, body = c.dev.get(f"{url}/releases/notes")
    notes = body.get("notes", "")
    r.check("drafted notes start from the previous release",
            body.get("previous_tag") == "v1.0.0" and "Fix the login redirect" in notes and f"(#{c.pr})" in notes, notes)
    s, body = c.dev.post(f"{url}/releases", {"version": "1.1.0", "notes": notes})
    r.check("a developer publishes 1.1.0 on main", s == 200 and body["release"]["commit_id"] == heads(c.lead, c.repo)["main"], body)
    s, body = c.lead.post(f"{url}/releases", {"version": "2.0.0-rc.1"})
    s, body = c.dev.get(f"{url}/releases")
    flags = {x["version"]: (x["latest"], x["prerelease"]) for x in body.get("releases", [])}
    r.check("latest is the highest stable version; the rc is a pre-release",
            flags.get("1.1.0") == (True, False) and flags.get("2.0.0-rc.1") == (False, True), flags)
    s, body = c.dev._call("PATCH", f"{url}/releases/1.1.0", json={"title": "Login"})
    r.check("a release is edited", s == 200 and body.get("changed") == ["title"], body)
    s, _ = c.dev._call("DELETE", f"{url}/releases/2.0.0-rc.1")
    r.check("...but a developer cannot delete one (403)", s == 403)
    s, body = c.lead._call("DELETE", f"{url}/releases/2.0.0-rc.1")
    r.check("a team lead withdraws the rc, keeping its tag",
            s == 200 and any(t["name"] == "v2.0.0-rc.1" for t in c.lead.get(f"{url}/tags")[1]["tags"]), body)
    s, body = c.lead._call("DELETE", f"{url}/tags/v1.0.0")
    r.check("a tag under a release is not deleted (409)", s == 409 and body["detail"]["code"] == "TAG_IN_USE", body)
    s, body = c.lead.post(f"{url}/tags", {"name": "v1.0.0"})
    r.check("a duplicate tag is 409, not 500", s == 409, body)
    s, body = c.dev.post(f"{url}/tags", {"name": "leak", "commit_id": c.foreign})
    r.check("a tag cannot name another repository's commit (404)", s == 404, body)
    s, _ = c.lead.post(f"{url}/tags", {"name": "release/1.0", "target": c.v1[:10]})
    s2, _ = c.lead._call("DELETE", f"{url}/tags/release/1.0")
    r.check("a tag with a slash, made from a short id, is deleted", s == 200 and s2 == 200)


def scenario_archives(r, c):
    r.section("4  Source archives")
    url = f"/api/repository/{c.repo}"
    response = c.dev.raw(f"{url}/source.zip", ref="v1.0.0")
    names = []
    if response.status_code == 200:
        with zipfile.ZipFile(io.BytesIO(response.content)) as archive:
            names = sorted(archive.namelist())
            app = archive.read("inventory-v1.0.0/app.py")
            logo = archive.read("inventory-v1.0.0/assets/logo.png")
    r.check("the files at v1.0.0 download as a zip under one folder",
            response.status_code == 200 and names == ["inventory-v1.0.0/app.py", "inventory-v1.0.0/assets/logo.png",
                                                      "inventory-v1.0.0/docs/handwritten.md"], names)
    r.check("...byte for byte", names and app == b"print('v1')\n" and logo == PNG)
    response = c.dev.raw(f"{url}/source.zip")
    r.check("no ref means the default branch", response.status_code == 200
            and response.headers.get("X-Zanbeel-Commit") == heads(c.lead, c.repo)["main"])
    r.check("an outsider gets 403", c.outsider.raw(f"{url}/source.zip").status_code == 403)
    r.check("an unknown ref is 404", c.dev.raw(f"{url}/source.zip", ref="no-such-ref").status_code == 404)


def scenario_docs(r, c, workdir, fake):
    r.section("5  Documentation through the real pipeline")
    url = f"/api/repository/{c.repo}"
    s, _ = c.outsider._call("POST", f"{url}/generate-project-docs", params={"selected_docs": "readme"})
    r.check("an outsider cannot generate (403)", s == 403)
    r.check("...nor read the status (403)", c.outsider.get(f"{url}/docs-status")[0] == 403)
    r.check("an anonymous read is 401, not 500", Api(c.base).get(f"{url}/docs")[0] == 401)

    c.lead.post(f"{url}/branches", {"name": "experiment", "from_branch": "main"})
    push(c.lead, c.repo, "lead", "experiment", {"app.py": "print('x')\n", "experiment.py": "x = 1\n"}, "experiment")
    main_before = heads(c.lead, c.repo)["main"]

    s, body = c.dev._call("POST", f"{url}/generate-project-docs",
                          params={"selected_docs": "readme,architecture"})
    job = wait_job(c.dev, c.repo)
    r.check("a developer's generation completes", s == 200 and job.get("status") == "completed", job)
    landing = (job.get("result") or {}).get("commit") or {}
    r.check("...and is kept, not committed: their changes go through review",
            landing.get("committed") is False and "review" in (landing.get("reason") or ""), landing)
    r.check("...so main has not moved", heads(c.lead, c.repo)["main"] == main_before)
    steps = {p["name"]: p["status"] for p in job.get("docs_progress") or []}
    r.check("the status listed the documents it was asked for", {"README.md", "Architecture"} <= set(steps), steps)

    readme_prompt = next((p for p in fake.prompts if "Document target: README.md" in p), "")
    r.check("the model was shown main as it is: no deleted file, no other branch",
            "app.py" in readme_prompt and "old.txt" not in readme_prompt and "experiment.py" not in readme_prompt)

    fake.prompts.clear()
    s, _ = c.lead._call("POST", f"{url}/generate-project-docs", params={"selected_docs": "readme,architecture"})
    job = wait_job(c.lead, c.repo)
    landing = (job.get("result") or {}).get("commit") or {}
    r.check("a team lead's generation is committed", landing.get("committed") is True, landing)
    tip = heads(c.lead, c.repo)["main"]
    files = tree(workdir, tip)
    before = tree(workdir, main_before)
    r.check("...on main, on top of the tip it describes", tip == landing.get("commit_id") and tip != main_before)
    r.check("...keeping every file main had (the image and the hand-written doc included)",
            set(before) <= set(files), sorted(set(before) - set(files)))
    r.check("...adding only documents, Word versions included",
            all(p.startswith("docs/") for p in set(files) - set(before))
            and "docs/project/README.md" in files and any(p.endswith(".docx") for p in files),
            sorted(set(files) - set(before)))
    r.check("...and nothing from history or other branches", "old.txt" not in files and "experiment.py" not in files)

    s, body = c.lead.get(f"/api/repository/{c.repo}/activity", params={"type": "generate_project_docs"})
    rows = body.get("activities", [])
    r.check("one activity row describes it, with the branch move inside",
            len(rows) >= 1 and rows[0].get("commit_id") == tip and (rows[0].get("payload") or {}).get("ref", {}).get("before") == main_before,
            rows[:1])

    s, listing = c.dev.get(f"{url}/docs")
    paths = [f["path"] for f in listing.get("files", [])]
    r.check("the listing uses forward slashes and hides the manifest",
            "project/README.md" in paths and not any(p.startswith(".") or "\\" in p for p in paths), paths)
    r.check("...and says the docs are up to date with main", listing.get("up_to_date") is True, listing.get("up_to_date"))
    page = c.dev.raw(f"{url}/docs/project/README.md")
    r.check("a document is served inert (nosniff, sandboxed)",
            page.status_code == 200 and page.headers.get("X-Content-Type-Options") == "nosniff"
            and "sandbox" in page.headers.get("Content-Security-Policy", ""))
    push(c.lead, c.repo, "lead", "main", {"app.py": "print('v3')\n",
                                          "assets/logo.png": PNG}, "newer code")
    r.check("after a push the docs say main has moved",
            c.dev.get(f"{url}/docs")[1].get("up_to_date") is False)

    c.lead.put(f"{url}/branch-protection", {"branch_pattern": "main", "mode": "protected"})
    protected_tip = heads(c.lead, c.repo)["main"]
    c.lead._call("POST", f"{url}/generate-project-docs", params={"selected_docs": "readme"})
    job = wait_job(c.lead, c.repo)
    landing = (job.get("result") or {}).get("commit") or {}
    r.check("with main protected, the documents are kept but not committed",
            landing.get("committed") is False and "protected" in (landing.get("reason") or "")
            and heads(c.lead, c.repo)["main"] == protected_tip, landing)
    r.check("...and the status says why", "protected" in (job.get("last_generation") or {}).get("commit_skipped_reason", ""))
    c.lead.put(f"{url}/branch-protection", {"branch_pattern": "main", "mode": "open"})


def scenario_cli(r, c, root):
    r.section("6  The fox CLI")
    home, work = root / "cli-home", root / "cli-work"
    home.mkdir()
    work.mkdir()
    env = {"FOXNEST_TOKEN": c.dev.token, "FOXNEST_SERVER": c.base, "FOXNEST_PROJECT_DOCS_MODEL": MODEL}
    code_, out = run_cli(work, home, ["generate-docs", "--repo-id", c.repo, "--docs", "readme"], env=env)
    r.check("fox generate-docs, as a developer, says the documents were kept and why",
            "not committed" in out and "review" in out and "Syncing generated docs" not in out, out[-1500:])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--keep", action="store_true", help="keep the work directory")
    parser.add_argument("--port", type=int, default=0)
    args = parser.parse_args()

    root = Path(tempfile.mkdtemp(prefix="zanbeel_e2e_repomgmt_"))
    workdir = root / "server"
    workdir.mkdir()
    fake = FakeOllama()
    report = Report()
    c = Ctx()
    try:
        extra = {
            "FOXNEST_DOCS_DIR": str(workdir / "docs"),
            "FOXNEST_OLLAMA_URL": fake.url,
            "FOXNEST_PROJECT_DOCS_MODEL": MODEL,
        }
        with live_server(workdir, args.port or free_port(), extra) as base:
            c.base = base
            scenario_setup(report, c, workdir)
            scenario_branches(report, c)
            scenario_releases(report, c)
            scenario_archives(report, c)
            scenario_docs(report, c, workdir, fake)
            scenario_cli(report, c, root)
    finally:
        fake.close()
        if args.keep:
            print(f"\nkept: {root}")
        else:
            remove_tree(root)
    sys.exit(0 if report.summary() else 1)


if __name__ == "__main__":
    main()
