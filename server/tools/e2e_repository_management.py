# --- a stand-in for Ollama --------------------------------------------------------------

_WORDS = ("module request handler storage schema client service worker queue cache route "
          "config record invoice ledger account session token report export import batch "
          "parser render index search audit policy release branch commit review deploy "
          "metric alert backup restore migrate verify archive notify upload stream retry").split()


class FakeOllama:
    """Answers /api/tags and /api/generate the way Ollama does, with a document that has
    every heading the prompt requires, distinct per document so the pipeline's
    near-duplicate check passes. Records every prompt."""

    def __init__(self):
        self.prompts = []
        outer = self

        class Handler(BaseHTTPRequestHandler):
            def log_message(self, *args):
                pass

            def _send(self, payload):
                data = json.dumps(payload).encode("utf-8")
                self.send_response(200)
                self.send_header("Content-Type", "application/json")
                self.send_header("Content-Length", str(len(data)))
                self.end_headers()
                self.wfile.write(data)

            def do_GET(self):
                self._send({"models": [{"name": MODEL}]})

            def do_POST(self):
                body = json.loads(self.rfile.read(int(self.headers.get("Content-Length") or 0)) or b"{}")
                prompt = body.get("prompt", "")
                outer.prompts.append(prompt)
                self._send({"response": outer.answer(prompt), "done": True})

        self.server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self.url = f"http://127.0.0.1:{self.server.server_address[1]}"
        threading.Thread(target=self.server.serve_forever, daemon=True).start()

    @staticmethod
    def answer(prompt):
        target = (re.search(r"(?:Document target|Target): (.+)", prompt) or [None, "Document"])[1].strip()
        project = (re.search(r"Project: (.+)", prompt) or [None, "the project"])[1].strip()
        match = re.search(r"Required headings:\n(\[.*?\])\n", prompt)
        headings = json.loads(match.group(1)) if match else ["## Overview"]
        lines = [f"# {target}: {project}", "",
                 f"This {target} describes {project} from the files on its default branch.", ""]
        for heading in headings:
            seed = hashlib.sha256(f"{target}|{heading}".encode()).digest()
            words = " ".join(_WORDS[b % len(_WORDS)] for b in seed[:24])
            lines += [heading, "", f"For the {target}, {heading.lstrip('# ')} covers: {words}.", ""]
        return "\n".join(lines)

    def close(self):
        self.server.shutdown()


