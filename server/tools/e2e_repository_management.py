#!/usr/bin/env python3
"""End-to-end check of Repository Management against a live server.

    ..\\venv\\Scripts\\python.exe tools/e2e_repository_management.py [--keep] [--port N]

Starts a real uvicorn server on a throwaway database, blob store, search index and docs
folder, plus a stand-in for Ollama, so documentation is generated by the server's real
pipeline -- prompts, per-document validation and retries, Word conversion -- end to end.
Drives branches, tags, releases, source archives and docs over HTTP and through the real
fox CLI, as a team lead, a developer and an outsider. Nothing touches the development
database or the development docs folder.

Each check prints PASS or FAIL; the run ends with a count and exits non-zero on any
failure, so it can gate a pull request.

Scenarios
  1  Setup
  2  Branches: the list, names with slashes, refusals, delete and restore
  3  Tags and releases: targets, drafted notes, edits, refusals, latest
  4  Source archives
  5  Documentation through the real pipeline: who may generate, what is committed
  6  The fox CLI: generate-docs reports where the documents went
"""

