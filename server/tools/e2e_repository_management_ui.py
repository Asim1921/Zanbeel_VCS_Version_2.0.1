#!/usr/bin/env python3
"""End-to-end check of branches, releases and tags, and documentation in a real browser.

    ..\\venv\\Scripts\\python.exe tools/e2e_repository_management_ui.py [--keep] [--headed]

Starts the backend on a throwaway database, blob store, search index and docs folder,
with a stand-in for Ollama so documentation is generated by the real pipeline; seeds a
repository with branches, a pull request, a release whose notes carry raw HTML and a
javascript: link, and generated documentation; starts the Vite dev server pointed at the
backend, and runs foxnestFrontend/scripts/e2e-repository-management-ui.mjs as the lead
and then as the developer. Afterwards it checks on the server what the browser did.

Needs Chrome (or Edge with --browser msedge) and, once:
    cd foxnestFrontend && npm i --no-save playwright-core
"""

import argparse
import os
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from e2e_repository_management import (  # noqa: E402
    MODEL, PASSWORD, PNG, FakeOllama, heads, push, seed, session_of, wait_job,
)
from e2e_merge_conflicts import Api, Report, free_port, live_server, remove_tree  # noqa: E402
from e2e_merge_conflicts_ui import start_frontend, stop  # noqa: E402

FRONTEND_ROOT = Path(__file__).resolve().parents[2] / "foxnestFrontend"
DRIVER = FRONTEND_ROOT / "scripts" / "e2e-repository-management-ui.mjs"

HOSTILE_NOTES = (
    "## Highlights\n\n"
    "- First public version\n"
    "- <img src=x onerror=\"window.__pwned = true\"> inline HTML must not render\n"
    "- [a link that must go nowhere](javascript:window.__pwned=true)\n\n"
    "<script>window.__pwned = true</script>\n"
)


def run_driver(report, url, phase, user, shots, args, **extra):
    env = dict(os.environ, FRONTEND_URL=url, E2E_USER=user, E2E_PASSWORD=PASSWORD, E2E_PHASE=phase,
               SCREENSHOT_DIR=str(shots), E2E_BROWSER=args.browser, E2E_HEADED="1" if args.headed else "0",
               **extra)
    driver = subprocess.run(["node", str(DRIVER)], cwd=FRONTEND_ROOT, env=env,
                            capture_output=True, text=True, encoding="utf-8", timeout=900)
    print(driver.stdout.rstrip())
    if driver.stderr.strip():
        print(driver.stderr.rstrip())
    for line in driver.stdout.splitlines():
        line = line.strip()
        if line.startswith("PASS"):
            report.passed += 1
        elif line.startswith("FAIL"):
            report.failed.append(f"UI {phase}: " + line[6:])
    report.check(f"browser phase '{phase}' finished", driver.returncode in (0, 1), f"exit {driver.returncode}")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--keep", action="store_true", help="Keep the temporary directory")
    parser.add_argument("--headed", action="store_true", help="Show the browser window")
    parser.add_argument("--browser", default="chrome", help="chrome or msedge")
    args = parser.parse_args()

    root = Path(tempfile.mkdtemp(prefix="zanbeel_e2e_repomgmt_ui_"))
    workdir = root / "server"
    workdir.mkdir()
    shots = root / "screenshots"
    report = Report()
    fake = FakeOllama()
    frontend = frontend_log = None
    try:
        api_port, ui_port = free_port(), free_port()
        ui_origin = f"http://127.0.0.1:{ui_port}"
        extra = {"CORS_ORIGINS": ui_origin, "FOXNEST_DOCS_DIR": str(workdir / "docs"),
                 "FOXNEST_OLLAMA_URL": fake.url, "FOXNEST_PROJECT_DOCS_MODEL": MODEL}
        with live_server(workdir, api_port, extra) as base:
            report.section("Setup")
            repo, _other = seed(workdir)
            lead, dev = Api(base, session_of(base, "lead")), Api(base, session_of(base, "dev"))
            url = f"/api/repository/{repo}"
            keep = {"assets/logo.png": PNG, "docs/handwritten.md": "# Ours\n"}
            push(lead, repo, "lead", "main", {"app.py": "print('v1')\n", **keep}, "first")
            v1 = heads(lead, repo)["main"]
            lead.post(f"{url}/branches", {"name": "feature/login", "from_branch": "main"})
            push(lead, repo, "lead", "feature/login", {"app.py": "print('v1')\n", "login.py": "a = 1\n", **keep}, "Add login")
            push(lead, repo, "lead", "feature/login", {"app.py": "print('v1')\n", "login.py": "a = 2\n", **keep}, "Polish login")
            push(lead, repo, "lead", "main", {"app.py": "print('v2')\n", **keep}, "Fix the login redirect")
            _s, body = lead.post(f"{url}/pull-requests", {"title": "Login", "source_branch": "feature/login",
                                                          "target_branch": "main"})
            s1, _ = lead.post(f"{url}/releases", {"version": "1.0.0", "target": v1, "title": "First",
                                                  "notes": HOSTILE_NOTES})
            lead._call("POST", f"{url}/generate-project-docs", params={"selected_docs": "readme,architecture"})
            job = wait_job(lead, repo)
            report.check("history, a pull request, a release with hostile notes, generated docs",
                         s1 == 200 and body.get("pull_request") and job.get("status") == "completed"
                         and (job.get("result") or {}).get("commit", {}).get("committed"), job)

            frontend, frontend_log, url_ui = start_frontend(ui_port, base, root / "vite.log")
            report.check("the web client is being served", True)

            report.section("Browser, as the lead")
            run_driver(report, url_ui, "lead", "lead", shots, args, E2E_REPO=repo)
            report.section("Browser, as the developer")
            run_driver(report, url_ui, "dev", "dev", shots, args, E2E_REPO=repo)

            report.section("Server state after the browser run")
            branches = heads(lead, repo)
            report.check("the branch renamed, deleted and restored in the browser exists",
                         "ui/renamed" in branches and "ui/topic" not in branches, sorted(branches))
            _s, body = lead.get(f"{url}/releases")
            published = {r["version"]: r for r in body.get("releases", [])}
            report.check("the release published in the browser carries the drafted notes",
                         "Fix the login redirect" in (published.get("1.1.0") or {}).get("notes", ""),
                         published.get("1.1.0"))
            _s, status = lead.get(f"{url}/docs-status")
            last = status.get("last_generation") or {}
            report.check("the developer's generation is the last one, kept and not committed",
                         last.get("generated_by") == "dev" and last.get("committed") is False, last)
            _s, body = lead.get(f"/api/repository/{repo}/activity", params={"type": "generate_project_docs"})
            committed = [a for a in body.get("activities", []) if (a.get("payload") or {}).get("committed")]
            report.check("the lead's two generations were committed, as one row each",
                         len(committed) == 2, [a.get("description") for a in body.get("activities", [])])
    except Exception as exc:
        import traceback
        traceback.print_exc()
        report.check("the run completed without an unexpected error", False, repr(exc))
    finally:
        if frontend is not None:
            stop(frontend)
            frontend_log.close()
        fake.close()
        if args.keep:
            print(f"\nkept: {root}")
        else:
            remove_tree(root)

    sys.exit(0 if report.summary() else 1)


if __name__ == "__main__":
    main()
